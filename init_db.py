import sqlite3


def create_and_fill_db():
    # Создаем подключение к файлу базы данных (он создастся в корне проекта)
    conn = sqlite3.connect("test_data.db")
    cursor = conn.cursor()

    # Создаем таблицу для поисковых запросов
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS search_queries (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            query TEXT NOT NULL,
            product_name TEXT NOT NULL
        )
    """)

    # Список наших товаров для заполнения (чистый синтаксис без опечаток)
    queries = [
        ("утюг", "Утюг"), ("холодильник", "Холодильник"),
        ("стиральная машина", "Стир. машина"), ("микроволновка", "Микроволновка"),
        ("пылесос", "Пылесос"), ("телевизор", "Телевизор"),
        ("ноутбук", "Ноутбук"), ("смартфон", "Смартфон"),
        ("наушники", "Наушники"), ("планшет", "Планшет"),
        ("плита", "Плита"), ("духовой шкаф", "Духовой шкаф"),
        ("вытяжка", "Вытяжка"), ("посудомойка", "Посудомойка"),
        ("чайник", "Чайник"), ("блендер", "Блендер"),
        ("тостер", "Тостер"), ("кофемашина", "Кофемашина"),
        ("мясорубка", "Мясорубка"), ("миксер", "Миксер"),
        ("фен", "Фен"), ("утюжок", "Утюжок")
    ]

    # Очищаем таблицу перед заполнением, чтобы данные не дублировались
    cursor.execute("DELETE FROM search_queries")

    # Записываем данные в БД
    cursor.executemany("INSERT INTO search_queries (query, product_name) VALUES (?, ?)", queries)

    conn.commit()
    conn.close()
    print("База данных test_data.db успешно создана и заполнена товарами!")

if __name__ == "main":
    create_and_fill_db()

